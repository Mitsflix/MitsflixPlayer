#!/usr/bin/env python3
"""Regenerate app/src/main/res/values*/mitsflix_brand_strings.xml.

Takes every string in the pinned OwnTV core version that names the app ("OwnTV") and writes an
app-level override saying "Mitsflix Player" instead, for every language. Run after each OwnTV merge:
    python3 tools/mitsflix/rebrand_strings.py
"""
import glob, os, re, shutil, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DST = os.path.join(ROOT, "app/src/main/res")
NEW_NAME = "Mitsflix Player"
# Strings about OwnTV's own services/projects stay as they are (they really are OwnTV's).
SKIP = re.compile(r"worker|fair_share|open_subtitles|translat|contribution|app_name|common_own_tv_user")
ELEMENT = re.compile(r'(<(string|plurals)\b[^>]*\bname="([^"]+)"[^>]*>.*?</\2>)', re.S)


def pinned_core() -> str:
    toml = open(os.path.join(ROOT, "gradle/libs.versions.toml"), encoding="utf-8").read()
    m = re.search(r'^owntvCore = "([^"]+)"', toml, re.M)
    if not m:
        sys.exit("owntvCore version not found in gradle/libs.versions.toml")
    return m.group(1)


def main() -> None:
    ver = pinned_core()
    tmp = tempfile.mkdtemp()
    try:
        subprocess.run(["git", "clone", "-q", "--depth", "1", "--branch", f"core-{ver}",
                        "https://github.com/ahXN00/OwnTV_Core", tmp], check=True)
        src = os.path.join(tmp, "core/src/main/res")
        for old in glob.glob(os.path.join(DST, "values*/mitsflix_brand_strings.xml")):
            os.remove(old)
        total = 0
        for d in sorted(glob.glob(os.path.join(src, "values*"))):
            out = []
            for f in sorted(glob.glob(os.path.join(d, "*.xml"))):
                if "donottranslate" in f:
                    continue
                for el, _kind, name in ELEMENT.findall(open(f, encoding="utf-8").read()):
                    if "OwnTV" in el and not SKIP.search(name):
                        out.append("    " + el.replace("OwnTV", NEW_NAME))
            if not out:
                continue
            q = os.path.join(DST, os.path.basename(d))
            os.makedirs(q, exist_ok=True)
            with open(os.path.join(q, "mitsflix_brand_strings.xml"), "w", encoding="utf-8") as fh:
                fh.write('<?xml version="1.0" encoding="utf-8"?>\n'
                         f'<!-- Generated by tools/mitsflix/rebrand_strings.py from OwnTV core {ver}. Do not edit. -->\n'
                         '<resources xmlns:xliff="urn:oasis:names:tc:xliff:document:1.2" '
                         'xmlns:tools="http://schemas.android.com/tools">\n' + "\n".join(out) + "\n</resources>\n")
            total += len(out)
        print(f"Re-branded {total} strings from OwnTV core {ver}.")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    main()
